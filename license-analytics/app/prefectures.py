PREFECTURES: dict[int, Prefecture] = {r[0]: Prefecture(*r) for r in _RAW}
REGIONS: list[str] = list(dict.fromkeys(p.region for p in PREFECTURES.values()))


def load_overrides() -> None:
    """data/population_projection.csv があれば人口推計値を差し替える。"""
    path = os.path.join(DATA_DIR, "population_projection.csv")
    if not os.path.exists(path):
        return
    with open(path, encoding="utf-8-sig") as f:
        for row in csv.DictReader(f):
            code = int(row["code"])
            base = PREFECTURES[code]
            PREFECTURES[code] = Prefecture(
                code, base.name, base.region,
                int(float(row.get("pop_2020", base.pop_2020))),
                int(float(row.get("pop_2035", base.pop_2035))),
                float(row.get("aged65_2020", base.aged65_2020)),
                float(row.get("aged65_2035", base.aged65_2035)),
                base.lat, base.lng,
            )


load_overrides()


def by_region(region: str) -> list[Prefecture]:
    return [p for p in PREFECTURES.values() if p.region == region]
