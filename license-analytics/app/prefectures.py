@dataclass(frozen=True)
class Prefecture:
    code: int
    name: str
    region: str
    pop_2020: int        # 千人
    pop_2035: int        # 千人（推計）
    aged65_2020: float   # %
    aged65_2035: float   # %
    lat: float
    lng: float

    @property
    def total_change_ratio(self) -> float:
        return self.pop_2035 / self.pop_2020

    def to_dict(self) -> dict:
        d = asdict(self)
        d["total_change_ratio"] = round(self.total_change_ratio, 4)
        return d


